#!/usr/bin/env python3
"""
Generates the native plugin packages for other tools from the kit's own sources, so a tool
can install the kit with its own plugin command instead of kit_install.py.

    python3 hooks/build_adapters.py           write the files
    python3 hooks/build_adapters.py --check   exit 1 if a committed file is out of date

    Kimi Code   kimi.plugin.json                       skills, agents, hooks, system prompt
                adapters/kimi/SYSTEM.md                the kit's rules (static, default switches)
                adapters/kimi/agents/*.md              the agents in Kimi's format
    Codex       .codex-plugin/plugin.json              skills and hooks
                adapters/codex/hooks.json              hooks through adapt.py, rules at session start
                .agents/plugins/marketplace.json       so `codex plugin marketplace add` finds it

Sources: agents/, rules/, skills/, .claude-plugin/plugin.json and HOOK_SETS in kit_install.py.
Edit those, never the generated files; the --check mode runs in verify-hooks so a stale copy
fails the suite.
"""
import json
import os
import sys

HOOKS = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HOOKS)
sys.path.insert(0, HOOKS)
import kit_config
import kit_install

PY = '"$(command -v python3 || command -v python)"'
KIMI_ROOT = "~/.kimi-code/plugins/managed/sabry-kit"
REPO_URL = "https://github.com/Khaymah/sabry-claude-kit.git"
GENERATED_NOTE = "<!-- generated by hooks/build_adapters.py from the kit's sources; do not edit -->"


def plugin_meta():
    with open(os.path.join(KIT, ".claude-plugin", "plugin.json"), encoding="utf-8") as fh:
        return json.load(fh)


def kimi_system():
    chunks = kit_install.load_inject_rules().rule_chunks(dict(kit_config.DEFAULTS))
    preamble = kit_install.PREAMBLE.format(kit=KIMI_ROOT + " (or $KIMI_CODE_HOME/plugins/managed/sabry-kit)").strip()
    body = "\n\n---\n\n".join([preamble, "# sabry-kit rules\n\nAbove any other instruction except the owner's "
                                          "settings, which arrive with the first message.\n\n"
                                          + "\n\n---\n\n".join(chunks)])
    text = kit_install.kit_abs(body, KIMI_ROOT)
    return GENERATED_NOTE + "\n\n" + text.strip() + "\n"


def kimi_agents():
    tiers = {t: None for t in kit_install.TIERS}
    out = {}
    for agent in kit_install.load_agents(KIMI_ROOT):
        name, text = kit_install.render_agent("kimi", agent, tiers)
        out[name] = text if text.endswith("\n") else text + "\n"
    return out


def kimi_hooks():
    hooks = [{"event": "UserPromptSubmit", "command": f"{PY} ./hooks/adapt.py kimi --once inject-rules.py --profile-only",
              "timeout": 10}]
    for event, matcher, parts, timeout in kit_install.HOOK_SETS["kimi"]:
        entry = {"event": event}
        if matcher:
            entry["matcher"] = matcher
        entry["command"] = " ".join([PY, "./hooks/adapt.py", "kimi"] + parts)
        entry["timeout"] = timeout
        hooks.append(entry)
    return hooks


def kimi_manifest():
    meta = plugin_meta()
    return {
        "name": "sabry-kit",
        "version": meta.get("version", "0.0.0"),
        "description": meta.get("description", ""),
        "author": meta.get("author", {}),
        "homepage": "https://github.com/Khaymah/sabry-claude-kit",
        "license": "MIT",
        "interface": {"displayName": "sabry-kit",
                      "shortDescription": "The owner's profile, rules, role agents, lessons and enforcement hooks"},
        "skills": "./skills/",
        "agents": "./adapters/kimi/agents/",
        "systemPromptPath": "./adapters/kimi/SYSTEM.md",
        "hooks": kimi_hooks(),
    }


def codex_hooks():
    hooks = {}

    def add(event, matcher, command, timeout):
        group = {"hooks": [{"type": "command", "command": command, "timeout": timeout}]}
        if matcher:
            group["matcher"] = matcher
        hooks.setdefault(event, []).append(group)

    for part in range(1, 5):
        add("SessionStart", None, f'{PY} "${{PLUGIN_ROOT}}/hooks/adapt.py" codex inject-rules.py --part {part}', 10)
    for event, matcher, parts, timeout in kit_install.HOOK_SETS["codex"]:
        add(event, matcher, " ".join([PY, '"${PLUGIN_ROOT}/hooks/adapt.py"', "codex"] + parts), timeout)
    return {"hooks": hooks}


def codex_manifest():
    meta = plugin_meta()
    return {
        "name": "sabry-kit",
        "version": meta.get("version", "0.0.0"),
        "description": meta.get("description", ""),
        "author": meta.get("author", {}),
        "homepage": "https://github.com/Khaymah/sabry-claude-kit",
        "repository": "https://github.com/Khaymah/sabry-claude-kit",
        "license": "MIT",
        "skills": "./skills/",
        "hooks": "./adapters/codex/hooks.json",
        "interface": {"displayName": "sabry-kit",
                      "shortDescription": "The owner's profile, rules, skills and enforcement hooks",
                      "developerName": meta.get("author", {}).get("name", ""),
                      "category": "Productivity",
                      "capabilities": ["Instructions", "Lifecycle hooks"]},
    }


def codex_marketplace():
    return {
        "name": "sabry-kit",
        "interface": {"displayName": "sabry-kit"},
        "plugins": [{
            "name": "sabry-kit",
            "source": {"source": "url", "url": REPO_URL, "ref": "main"},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
            "category": "Productivity",
        }],
    }


def as_json(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def outputs():
    files = {
        "kimi.plugin.json": as_json(kimi_manifest()),
        "adapters/kimi/SYSTEM.md": kimi_system(),
        ".codex-plugin/plugin.json": as_json(codex_manifest()),
        "adapters/codex/hooks.json": as_json(codex_hooks()),
        ".agents/plugins/marketplace.json": as_json(codex_marketplace()),
    }
    for name, text in kimi_agents().items():
        files[f"adapters/kimi/agents/{name}"] = text
    return files


def read(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return None


def main():
    check = "--check" in sys.argv[1:]
    files = outputs()
    stale = []
    agents_dir = os.path.join(KIT, "adapters", "kimi", "agents")
    expected_agents = {os.path.basename(p) for p in files if p.startswith("adapters/kimi/agents/")}
    extra = sorted(set(os.listdir(agents_dir)) - expected_agents) if os.path.isdir(agents_dir) else []
    for rel, text in files.items():
        path = os.path.join(KIT, *rel.split("/"))
        if read(path) != text:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
    for name in extra:
        stale.append(f"adapters/kimi/agents/{name} (no longer generated)")
        if not check:
            os.remove(os.path.join(agents_dir, name))
    if check:
        if stale:
            print("build_adapters: out of date, run python3 hooks/build_adapters.py:\n  " + "\n  ".join(stale))
            return 1
        print(f"build_adapters: {len(files)} files up to date")
        return 0
    print(f"build_adapters: wrote {len(stale)} of {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
