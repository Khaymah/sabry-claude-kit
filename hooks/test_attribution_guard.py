"""Tests for attribution-guard.py and the workflow it installs: the workflow lands only in
GitHub repositories the owner allows, an owner's own workflow is never replaced, and the
cleaner removes attribution lines without touching ordinary text."""
import json
import os
import subprocess
import sys
import tempfile
import textwrap
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HERE)
SCRIPT = os.path.join(HERE, "attribution-guard.py")
TEMPLATE = os.path.join(KIT, "Templates", "no-ai-attribution.yml")
WORKFLOW = os.path.join(".github", "workflows", "no-ai-attribution.yml")
FOOT = "Generated by " + "[Claude Code](https://claude.ai/code/session_01ABC)"


def cleaner():
    with open(TEMPLATE, encoding="utf-8") as fh:
        text = fh.read()
    code = textwrap.dedent(text.split("python3 - <<'PY'\n")[1].split("\n          PY", 1)[0])
    scope = {}
    os.environ.setdefault("GH_TOKEN", "x")
    os.environ.setdefault("GITHUB_REPOSITORY", "o/r")
    exec(code.split("event = json.load")[0], scope)
    return scope["clean"]


def author_check():
    with open(TEMPLATE, encoding="utf-8") as fh:
        text = fh.read()
    code = textwrap.dedent(text.split("python3 - <<'PY'\n")[2].split("\n          PY", 1)[0])
    scope = {}
    os.environ.setdefault("GH_TOKEN", "x")
    os.environ.setdefault("GITHUB_REPOSITORY", "o/r")
    exec(code.split("def get(")[0], scope)
    return scope["offenders"]


class GuardTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.home = os.path.join(self.tmp.name, "home")
        self.proj = os.path.join(self.tmp.name, "proj")
        os.makedirs(self.home)
        os.makedirs(self.proj)
        self.git("init", "-q", "-b", "main")
        self.git("remote", "add", "origin", "https://github.com/Acme/shop.git")
        self.env = {k: v for k, v in os.environ.items()
                    if not k.startswith("SABRY_KIT_") and k not in ("CLAUDE_CONFIG_DIR", "CLAUDE_PROJECT_DIR")}
        self.env.update(HOME=self.home, USERPROFILE=self.home)

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args):
        return subprocess.run(["git", "-C", self.proj] + list(args), capture_output=True, text=True, timeout=30)

    def run_guard(self, *args, payload=None, env=None):
        e = dict(self.env)
        e.update(env or {})
        data = {"cwd": self.proj, "session_id": "s1"}
        data.update(payload or {})
        p = subprocess.run([sys.executable, SCRIPT] + list(args), input=json.dumps(data), capture_output=True,
                           text=True, env=e, cwd=self.proj, timeout=60)
        self.assertEqual(p.returncode, 0, p.stderr)
        if not p.stdout.strip() or args[:1] == ("status",):
            return p.stdout.strip()
        return json.loads(p.stdout)["hookSpecificOutput"]["additionalContext"]

    def path(self, rel):
        return os.path.join(self.proj, rel)

    def read(self, rel):
        with open(self.path(rel), encoding="utf-8") as fh:
            return fh.read()

    def test_installs_once_in_a_github_repo(self):
        note = self.run_guard()
        self.assertIn("was installed", note)
        self.assertIn("default branch", note)
        with open(TEMPLATE, encoding="utf-8") as fh:
            self.assertEqual(self.read(WORKFLOW), fh.read())
        settings = json.loads(self.read(os.path.join(".claude", "settings.json")))
        self.assertEqual(settings["attribution"], {"commit": "", "pr": "", "sessionUrl": False})
        self.assertEqual(self.run_guard(), "", "nothing to do the second time")

    def test_existing_settings_are_merged_not_replaced(self):
        os.makedirs(self.path(".claude"))
        with open(self.path(os.path.join(".claude", "settings.json")), "w") as fh:
            json.dump({"permissions": {"allow": ["Bash(ls)"]}, "attribution": {"commit": "x", "other": 1}}, fh)
        self.run_guard()
        settings = json.loads(self.read(os.path.join(".claude", "settings.json")))
        self.assertEqual(settings["permissions"], {"allow": ["Bash(ls)"]})
        self.assertEqual(settings["attribution"], {"commit": "", "pr": "", "sessionUrl": False, "other": 1})

    def test_owner_files_are_left_alone(self):
        os.makedirs(os.path.dirname(self.path(WORKFLOW)))
        with open(self.path(WORKFLOW), "w") as fh:
            fh.write("name: mine\n")
        os.makedirs(self.path(".claude"))
        with open(self.path(os.path.join(".claude", "settings.json")), "w") as fh:
            fh.write("{ // comment\n}")
        self.assertEqual(self.run_guard(), "")
        self.assertEqual(self.read(WORKFLOW), "name: mine\n")
        self.assertEqual(self.read(os.path.join(".claude", "settings.json")), "{ // comment\n}")

    def test_an_older_kit_workflow_is_updated(self):
        os.makedirs(os.path.dirname(self.path(WORKFLOW)))
        with open(self.path(WORKFLOW), "w") as fh:
            fh.write("# sabry-kit:no-ai-attribution v0\nname: old\n")
        self.assertIn("was updated", self.run_guard())
        self.assertIn("pull_request_target", self.read(WORKFLOW))

    def test_not_a_github_repo_switch_off_and_owner_allowlist(self):
        self.git("remote", "set-url", "origin", "https://gitlab.com/acme/shop.git")
        self.assertEqual(self.run_guard(), "")
        self.assertFalse(os.path.exists(self.path(WORKFLOW)))
        self.git("remote", "set-url", "origin", "git@github.com:Acme/shop.git")
        self.assertEqual(self.run_guard(env={"SABRY_KIT_ATTRIBUTION_GUARD": "0"}), "")
        os.makedirs(os.path.join(self.home, ".agents"))
        with open(os.path.join(self.home, ".agents", "profile.json"), "w") as fh:
            json.dump({"name": "Mona", "github_owners": ["mona-dev"]}, fh)
        self.assertEqual(self.run_guard(), "", "Acme is not on the owner's list")
        with open(os.path.join(self.home, ".agents", "profile.json"), "w") as fh:
            json.dump({"name": "Mona", "github_owners": ["ACME"]}, fh)
        self.assertIn("was installed", self.run_guard())

    def test_project_profile_cannot_switch_the_guard_off(self):
        os.makedirs(self.path(".agents"))
        with open(self.path(os.path.join(".agents", "profile.json")), "w") as fh:
            json.dump({"settings": {"attribution_guard": False}}, fh)
        self.assertIn("was installed", self.run_guard())

    def test_after_a_pr_write_says_when_the_workflow_is_not_live(self):
        payload = {"tool_name": "Bash", "tool_input": {"command": "gh pr create --title x --body y"}}
        note = self.run_guard("--after", payload=payload)
        self.assertIn("does not have", note)
        self.assertEqual(self.run_guard("--after", payload=payload), "", "once per session")
        self.assertEqual(self.run_guard("--after", payload={"tool_name": "Bash", "session_id": "s2",
                                                           "tool_input": {"command": "ls"}}), "")

    def test_status_reports(self):
        self.run_guard()
        status = json.loads(self.run_guard("status"))
        self.assertEqual((status["github_repo"], status["workflow"]), ("Acme/shop", "kit"))
        self.assertTrue(status["workflow_current"] and status["settings_attribution_off"])
        self.assertFalse(status["workflow_on_default_branch"])

    def test_cleaner_removes_attribution_and_nothing_else(self):
        clean = cleaner()
        robot = "\U0001F916 Generated with " + "[Claude Code](https://claude.com/claude-code)"
        trailer = "Co-Authored-By: " + "Claude Fable 5.2 <noreply@anthropic.com>"
        cases = {
            "Fix login\n\nDetails.\n\n---\n_" + FOOT + "_": "Fix login\n\nDetails.",
            "Body\n\n" + robot + "\n\nhttps://claude.ai/code/" + "session_01X\n": "Body\n",
            "feat: x\n\n" + trailer + "\nClaude-Session: https://x": "feat: x",
            "Keep --- this\n\n---\n\nand this\n": "Keep --- this\n\n---\n\nand this\n",
            "We use Claude Code for reviews.": "We use Claude Code for reviews.",
            "a\r\nb\r\n\r\n---\r\n_" + FOOT + "_\r\n": "a\r\nb\r\n",
            "": "",
        }
        for before, after in cases.items():
            self.assertEqual(clean(before), after, before)
        self.assertIsNone(clean(None))

    def test_author_check_flags_ai_commits_only(self):
        offenders = author_check()
        def commit(sha, author, committer=("GitHub", "noreply@github.com")):
            return {"sha": sha, "commit": {"author": {"name": author[0], "email": author[1]},
                                           "committer": {"name": committer[0], "email": committer[1]}}}
        commits = [
            commit("a" * 40, ("Sabry Dawood", "owner@example.com")),
            commit("b" * 40, ("Claude", "noreply@anthropic.com"), ("Claude", "noreply@anthropic.com")),
            commit("c" * 40, ("Sabry Dawood", "owner@example.com"), ("Codex", "codex@example.com")),
            commit("d" * 40, ("dependabot[bot]", "49699333+dependabot[bot]@users.noreply.github.com")),
            commit("e" * 40, ("Claudette Smith", "claudette@example.com")),
        ]
        found = offenders(commits)
        self.assertEqual([(s, r) for s, r, _ in found], [("bbbbbbb", "author"), ("bbbbbbb", "committer"), ("ccccccc", "committer")])

    def test_author_job_has_read_only_permissions(self):
        with open(TEMPLATE, encoding="utf-8") as fh:
            job = fh.read().split("  authors:", 1)[1]
        self.assertIn("contents: read", job)
        self.assertNotIn(": write", job)

    def test_workflow_never_checks_out_or_interpolates_untrusted_text(self):
        with open(TEMPLATE, encoding="utf-8") as fh:
            text = fh.read()
        self.assertNotIn("actions/checkout", text)
        self.assertNotIn("github.event.pull_request.body", text)
        self.assertNotIn("github.event.comment.body", text)
        self.assertNotIn("github.event.pull_request.title", text)
        self.assertIn("GITHUB_EVENT_PATH", text)


if __name__ == "__main__":
    unittest.main()
