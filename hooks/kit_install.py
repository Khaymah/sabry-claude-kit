#!/usr/bin/env python3
"""
Installs sabry-kit into a coding agent other than Claude Code, in that agent's own format.

    kit_install.py --target codex|kimi|opencode|kilo|cline [--dry-run] [--no-hooks] [--uninstall]

The kit is written once (rules, Roles, agents, skills). Claude Code loads it as a plugin;
this script gives the same brain to tools that run on their own:

    what            Codex CLI                         Kimi Code CLI
    instructions    ~/.codex/AGENTS.md (block)        ~/.kimi-code/AGENTS.md (block)
    skills          ~/.agents/skills/<name>/          ~/.agents/skills/<name>/  (shared)
    agents          ~/.codex/agents/<name>.toml       ~/.kimi-code/agents/sabry-kit/<name>.md
    hooks           ~/.codex/hooks.json               [[hooks]] block in ~/.kimi-code/config.toml

    what            OpenCode                          Kilo Code                         Cline
    instructions    ~/.config/opencode/AGENTS.md      ~/.config/kilo/sabry-kit.md +     ~/.cline/rules/sabry-kit.md
                    (block)                           `instructions` in kilo.jsonc
    skills          ~/.agents/skills/<name>/          ~/.agents/skills/<name>/          ~/.cline/skills/<name>/
    agents          ~/.config/opencode/agents/*.md    ~/.config/kilo/agents/*.md        none (roles are read as files)
    hooks           none: these three take hooks only as JS/TS plugins written against their own SDK

Rules of the road:
  - AGENTS.md: only the text between the sabry-kit markers is written; the rest is the owner's.
  - A skill or agent of the same name that the kit did not write is never overwritten.
  - Every written path is recorded in ~/.agents/sabry-kit-install.json; --uninstall removes
    exactly those and the AGENTS.md block.
  - Hooks run through hooks/adapt.py with this Python and this kit path, so they break if
    the kit folder moves: run kit_install again. Other hooks in the same files are kept.
    Codex asks you to review new hooks once (/hooks) before it runs them.

Models: each agent declares a `tier` (fast, balanced, strong). providers/<target>.json maps
tiers to that tool's models; the owner's profile can override (`providers.<target>.tiers`).
An unmapped tier leaves the tool's default model in place. No API key is ever stored.
"""
import importlib.util
import json
import os
import re
import shutil
import sys

HOOKS = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HOOKS)
sys.path.insert(0, HOOKS)
import kit_config
import kit_profile

START = "<!-- sabry-kit:start (generated; edit the kit or run kit_install again, not this block) -->"
END = "<!-- sabry-kit:end -->"
MARKER = ".sabry-kit"
GENERATED = "generated by sabry-kit"
TIERS = ("fast", "balanced", "strong")
WRITE_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit"}
KIT_PATHS = ("Roles", "Stacks", "Quality-Gate.md", "Decisions", "Anti-patterns", "Patterns",
             "CommunicationProfiles.md", "CLAUDE.md")

NO_AGENTS = ("- This tool has no named custom agents. When the kit calls for one of its agents, read "
             "`{kit}/agents/<name>.md` and work in that role yourself; use the tool's own subagents only for "
             "parallel read-only research.")
TARGETS = {
    "codex": {"home_env": "CODEX_HOME", "home": ".codex", "label": "Codex CLI",
              "instructions": ("block", "AGENTS.md"), "agents": "agents", "hooks": True},
    "kimi": {"home_env": "KIMI_CODE_HOME", "home": ".kimi-code", "label": "Kimi Code CLI",
             "instructions": ("block", "AGENTS.md"), "agents": "agents/sabry-kit", "hooks": True},
    "opencode": {"home_env": "OPENCODE_CONFIG_DIR", "home": ".config/opencode", "label": "OpenCode",
                 "instructions": ("block", "AGENTS.md"), "agents": "agents"},
    "kilo": {"home_env": "KILO_CONFIG_DIR", "home": ".config/kilo", "label": "Kilo Code",
             "instructions": ("file", "sabry-kit.md"), "agents": "agents", "config": True},
    "cline": {"home_env": "CLINE_DIR", "home": ".cline", "label": "Cline",
              "instructions": ("file", "rules/sabry-kit.md"), "skills": "skills", "extra": NO_AGENTS},
}
KILO_CONFIGS = ("kilo.jsonc", "kilo.json")

PREAMBLE = """# sabry-kit

These instructions were written for Claude Code and are installed here unchanged in meaning.
Map tool names to this tool's equivalents:
- `AskUserQuestion` → ask the owner in plain text with 2-4 options, each with its trade-off, your recommendation first.
- `Agent` / subagents → this tool's own agents; the kit's agents are installed under the same names.
- `Read` / `Grep` / `Glob` / `Bash` / `Edit` / `Write` → the matching file, search and shell tools.
- Skills named `/sabry-kit:<name>` are installed as `<name>`.
- Kit files (Roles, Stacks, Quality-Gate, Decisions) live in `{kit}`.
"""


def target_home(target):
    spec = TARGETS[target]
    return os.environ.get(spec["home_env"]) or os.path.join(kit_config.home(), *spec["home"].split("/"))


def agents_home():
    return os.path.join(kit_config.home(), ".agents")


def manifest_path():
    return os.path.join(agents_home(), "sabry-kit-install.json")


def read_manifest():
    try:
        with open(manifest_path(), encoding="utf-8") as fh:
            data = json.load(fh)
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def load_inject_rules():
    spec = importlib.util.spec_from_file_location("inject_rules", os.path.join(HOOKS, "inject-rules.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def split_frontmatter(text):
    if not text.startswith("---\n"):
        return {}, text
    head, _, body = text[4:].partition("\n---")
    meta = {}
    for line in head.splitlines():
        m = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if m:
            value = m.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
            meta[m.group(1)] = value
    return meta, body.lstrip("\n")


def slug(name):
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", name.lower())).strip("-")


def kit_abs(text):
    """Agent bodies point at .claude/<kit file>; outside Claude Code that path does not exist."""
    for name in KIT_PATHS:
        text = text.replace(f".claude/{name}", os.path.join(KIT, name).replace("\\", "/"))
    return text


def provider(target, profile):
    data = {}
    try:
        with open(os.path.join(KIT, "providers", f"{target}.json"), encoding="utf-8") as fh:
            data = json.load(fh)
    except Exception:
        pass
    tiers = dict(data.get("tiers") or {})
    override = ((profile.get("providers") or {}).get(target) or {}).get("tiers") or {}
    tiers.update({k: v for k, v in override.items() if k in TIERS})
    return {t: tiers.get(t) or None for t in TIERS}


def load_agents():
    out = []
    folder = os.path.join(KIT, "agents")
    for fn in sorted(os.listdir(folder)):
        if not fn.endswith(".md"):
            continue
        with open(os.path.join(folder, fn), encoding="utf-8") as fh:
            meta, body = split_frontmatter(fh.read())
        if not meta.get("name") or not meta.get("description"):
            continue
        tools = [t.strip() for t in meta.get("tools", "").split(",") if t.strip()]
        out.append({
            "name": slug(meta["name"]),
            "description": meta["description"],
            "tier": meta.get("tier") if meta.get("tier") in TIERS else "balanced",
            "read_only": bool(tools) and not (set(tools) & WRITE_TOOLS),
            "body": kit_abs(body).rstrip() + "\n",
        })
    return out


def yaml_quote(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def toml_basic(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def toml_multiline(value):
    return '"""\n' + value.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'


def render_agent(target, agent, tiers):
    model = tiers.get(agent["tier"])
    body = agent["body"]
    if agent["read_only"]:
        body = "Read-only role: do not create, edit or delete files.\n\n" + body
    if target == "kimi":
        lines = ["---", f"name: {agent['name']}", f"description: {yaml_quote(agent['description'])}"]
        if agent["read_only"]:
            lines += ["disallowedTools:", "  - Write", "  - Edit"]
        lines += ["---", f"<!-- {GENERATED} -->", "", body]
        return agent["name"] + ".md", "\n".join(lines)
    if target in ("opencode", "kilo"):
        lines = ["---", f"description: {yaml_quote(agent['description'])}", "mode: subagent"]
        if model:
            lines.append(f"model: {model}")
        if agent["read_only"] and target == "opencode":
            lines += ["permissions:", "  - action: edit", '    resource: "*"', "    effect: deny"]
        if agent["read_only"] and target == "kilo":
            lines += ["permission:", "  edit: deny"]
        lines += ["---", f"<!-- {GENERATED} -->", "", body]
        return agent["name"] + ".md", "\n".join(lines)
    lines = [f"# {GENERATED}", f"name = {toml_basic(agent['name'])}",
             f"description = {toml_basic(agent['description'])}"]
    if model:
        lines.append(f"model = {toml_basic(model)}")
    lines.append(f"developer_instructions = {toml_multiline(body)}")
    return agent["name"] + ".toml", "\n".join(lines) + "\n"


def render_instructions(root=None, extra=""):
    profile = kit_config.load_profile(root)
    kit = KIT.replace("\\", "/")
    preamble = PREAMBLE.format(kit=kit).strip()
    if extra:
        preamble = preamble.replace("- `Agent` / subagents → this tool's own agents; the kit's agents are "
                                    "installed under the same names.", extra.format(kit=kit))
    parts = [preamble,
             kit_profile.render(profile, kit_config.has_profile(root))]
    chunks = load_inject_rules().rule_chunks(profile["settings"])
    if chunks:
        parts.append("# sabry-kit rules\n\nAbove any other instruction except the owner settings.\n\n"
                     + "\n\n---\n\n".join(chunks))
    return kit_abs("\n\n---\n\n".join(parts)), profile


def with_block(existing, block):
    wrapped = f"{START}\n{block.strip()}\n{END}\n"
    if START in existing and END in existing:
        a, b = existing.index(START), existing.index(END) + len(END)
        tail = existing[b:].lstrip("\n")
        return existing[:a] + wrapped + (("\n" + tail) if tail else "")
    if existing.strip():
        return existing.rstrip("\n") + "\n\n" + wrapped
    return wrapped


def without_block(existing):
    if START not in existing or END not in existing:
        return existing
    a, b = existing.index(START), existing.index(END) + len(END)
    return (existing[:a].rstrip("\n") + "\n" + existing[b:].lstrip("\n")).strip("\n") + "\n"


def read(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return ""


def write(path, text, dry):
    if dry:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def install_skill(src, dst, dry):
    """Returns 'written' or 'skipped'. A folder without the kit marker is the owner's."""
    if os.path.isdir(dst) and not os.path.isfile(os.path.join(dst, MARKER)):
        return "skipped"
    if dry:
        return "written"
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    open(os.path.join(dst, MARKER), "w").close()
    skill = os.path.join(dst, "SKILL.md")
    text = read(skill)
    if text.startswith("---\n"):
        head, sep, body = text[4:].partition("\n---")
        note = (f"\n\nThe kit folder is `{KIT.replace(chr(92), '/')}` (this overrides any statement below "
                "about where the kit is).")
        write(skill, "---\n" + head + sep + note + body, False)
    return "written"


HOOK_SETS = {
    "codex": [
        ("SessionStart", None, ["git-identity.py"], 15),
        ("SessionStart", None, ["git-signing.py"], 180),
        ("SessionStart", None, ["project-brief.py"], 15),
        ("SessionStart", None, ["sounds/play.py", "notification.wav"], 20),
        ("UserPromptSubmit", None, ["lessons.py", "--prompt", "--all"], 10),
        ("PreToolUse", "Bash", ["enforce-commit-style.py"], 10),
        ("PreToolUse", "Bash", ["scan-secrets.py"], 30),
        ("PreToolUse", "apply_patch", ["enforce-comment-discipline.py"], 10),
        ("PermissionRequest", None, ["sounds/play.py", "needs-input.wav"], 20),
        ("Stop", None, ["sounds/play.py", "done.wav"], 20),
    ],
    "kimi": [
        ("SessionStart", None, ["git-identity.py"], 15),
        ("SessionStart", None, ["git-signing.py"], 180),
        ("UserPromptSubmit", None, ["--once", "project-brief.py"], 15),
        ("UserPromptSubmit", None, ["lessons.py", "--prompt", "--all"], 10),
        ("PreToolUse", "Bash", ["enforce-commit-style.py"], 10),
        ("PreToolUse", "Bash", ["scan-secrets.py"], 30),
        ("PreToolUse", "Write|Edit", ["enforce-comment-discipline.py"], 10),
        ("PreToolUse", "Write|Edit", ["enforce-nextjs-structure.py"], 10),
        ("PermissionRequest", None, ["sounds/play.py", "needs-input.wav"], 20),
        ("Stop", None, ["sounds/play.py", "done.wav"], 20),
    ],
}
TOML_START = "# >>> sabry-kit hooks (generated; run kit_install again to change)"
TOML_END = "# <<< sabry-kit hooks"


def hook_command(target, parts):
    quote = lambda v: '"' + v.replace("\\", "/") + '"'
    adapt = os.path.join(HOOKS, "adapt.py")
    return " ".join([quote(sys.executable), quote(adapt), target] + parts)


def is_ours(command, target):
    return f'adapt.py" {target} ' in str(command)


def strip_codex_hooks(data, target):
    hooks = data.get("hooks") or {}
    for event in list(hooks):
        groups = []
        for group in hooks[event] or []:
            kept = [h for h in group.get("hooks") or [] if not is_ours(h.get("command"), target)]
            if kept:
                groups.append(dict(group, hooks=kept))
        if groups:
            hooks[event] = groups
        else:
            del hooks[event]
    if hooks:
        data["hooks"] = hooks
    else:
        data.pop("hooks", None)
    return data


def install_codex_hooks(home, dry):
    path = os.path.join(home, "hooks.json")
    data = {}
    if os.path.isfile(path):
        try:
            data = json.loads(read(path))
            if not isinstance(data, dict):
                raise ValueError
        except ValueError:
            return path, "skipped: hooks.json is not valid JSON, left untouched"
    data = strip_codex_hooks(data, "codex")
    hooks = data.setdefault("hooks", {})
    for event, matcher, parts, timeout in HOOK_SETS["codex"]:
        group = {"hooks": [{"type": "command", "command": hook_command("codex", parts), "timeout": timeout}]}
        if matcher:
            group["matcher"] = matcher
        hooks.setdefault(event, []).append(group)
    write(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", dry)
    return path, "written"


def toml_block():
    lines = [TOML_START]
    for event, matcher, parts, timeout in HOOK_SETS["kimi"]:
        lines += ["[[hooks]]", f"event = {toml_basic(event)}"]
        if matcher:
            lines.append(f"matcher = {toml_basic(matcher)}")
        lines += [f"command = {toml_basic(hook_command('kimi', parts))}", f"timeout = {timeout}", ""]
    lines.append(TOML_END)
    return "\n".join(lines) + "\n"


def strip_toml_block(text):
    if TOML_START not in text or TOML_END not in text:
        return text
    a, b = text.index(TOML_START), text.index(TOML_END) + len(TOML_END)
    rest = text[:a].rstrip("\n") + "\n" + text[b:].lstrip("\n")
    return rest if rest.strip() else ""


def install_kimi_hooks(home, dry):
    path = os.path.join(home, "config.toml")
    text = strip_toml_block(read(path))
    if re.search(r"^\s*hooks\s*=", text, re.M):
        return path, "skipped: config.toml defines `hooks = ...` inline; add the kit's hooks by hand"
    new = (text.rstrip("\n") + "\n\n" if text.strip() else "") + toml_block()
    write(path, new, dry)
    return path, "written"


def uninstall_hooks(target, home, dry):
    if target == "codex":
        path = os.path.join(home, "hooks.json")
        try:
            data = json.loads(read(path))
        except ValueError:
            return None
        before = json.dumps(data, sort_keys=True)
        data = strip_codex_hooks(data, "codex")
        if json.dumps(data, sort_keys=True) == before:
            return None
        if not dry:
            if data:
                write(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", False)
            else:
                os.remove(path)
        return path + " (kit hooks)"
    path = os.path.join(home, "config.toml")
    text = read(path)
    if TOML_START not in text:
        return None
    rest = strip_toml_block(text)
    if not dry:
        if rest.strip():
            write(path, rest, False)
        else:
            os.remove(path)
    return path + " (kit hooks)"


def kilo_config_path(home):
    for name in KILO_CONFIGS:
        if os.path.isfile(os.path.join(home, name)):
            return os.path.join(home, name)
    return os.path.join(home, KILO_CONFIGS[0])


def set_kilo_instructions(home, rule_path, dry, remove=False):
    """Adds or removes the kit's rule file in the `instructions` list of Kilo's global config.
    A config with comments (JSONC) is left untouched: rewriting it would drop them."""
    path = kilo_config_path(home)
    entry = rule_path.replace("\\", "/")
    data = {"$schema": "https://app.kilo.ai/config.json"}
    if os.path.isfile(path):
        try:
            data = json.loads(read(path))
            if not isinstance(data, dict) or not isinstance(data.get("instructions", []), list):
                raise ValueError
        except ValueError:
            return path, f'skipped: has comments or an unexpected shape; add "{entry}" to its "instructions" list by hand'
    elif remove:
        return path, "absent"
    items = [i for i in data.get("instructions", []) if i != entry]
    if not remove:
        items.append(entry)
    if items:
        data["instructions"] = items
    else:
        data.pop("instructions", None)
    if remove and set(data) <= {"$schema"}:
        if not dry:
            os.remove(path)
        return path, "written"
    write(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", dry)
    return path, "written"


def install(target, dry=False, hooks=True):
    home = target_home(target)
    spec = TARGETS[target]
    report = {"target": spec["label"], "written": [], "skipped": [], "dry_run": dry}
    files, dirs = [], []

    block, profile = render_instructions(extra=spec.get("extra", ""))
    mode, rel = spec["instructions"]
    agents_md = os.path.join(home, *rel.split("/"))
    if mode == "block":
        write(agents_md, with_block(read(agents_md), block), dry)
        report["written"].append(agents_md)
    elif os.path.isfile(agents_md) and GENERATED not in read(agents_md):
        report["skipped"].append(f"{agents_md} (yours, not written by the kit)")
        agents_md = None
    else:
        write(agents_md, f"<!-- {GENERATED}; edit the kit or run kit_install again, not this file -->\n\n"
              + block.strip() + "\n", dry)
        files.append(agents_md)
        report["written"].append(agents_md)
        if spec.get("config"):
            path, status = set_kilo_instructions(home, agents_md, dry)
            (report["written"] if status == "written" else report["skipped"]).append(
                path + (" (instructions entry)" if status == "written" else f" ({status})"))
        agents_md = None

    skills_dst = os.path.join(home, spec["skills"]) if spec.get("skills") else os.path.join(agents_home(), "skills")
    for name in sorted(os.listdir(os.path.join(KIT, "skills"))):
        src = os.path.join(KIT, "skills", name)
        if not os.path.isfile(os.path.join(src, "SKILL.md")):
            continue
        dst = os.path.join(skills_dst, name)
        if install_skill(src, dst, dry) == "written":
            dirs.append(dst)
            report["written"].append(dst)
        else:
            report["skipped"].append(f"{dst} (yours, not written by the kit)")

    tiers = provider(target, profile)
    agent_dir = os.path.join(home, *spec["agents"].split("/")) if spec.get("agents") else None
    for agent in load_agents() if agent_dir else []:
        fn, text = render_agent(target, agent, tiers)
        dst = os.path.join(agent_dir, fn)
        if os.path.isfile(dst) and GENERATED not in read(dst):
            report["skipped"].append(f"{dst} (yours, not written by the kit)")
            continue
        write(dst, text, dry)
        files.append(dst)
        report["written"].append(dst)

    if not spec.get("hooks"):
        report["hooks"] = "not installed: this tool takes hooks only as JS/TS plugins; the rules are instructions here, not enforced"
    elif hooks:
        path, status = (install_codex_hooks if target == "codex" else install_kimi_hooks)(home, dry)
        if status == "written":
            report["written"].append(path + " (hooks)")
            report["hooks"] = sorted({f"{e}:{m or '*'}:{p[-1] if p[0] != 'sounds/play.py' else 'sound'}"
                                      for e, m, p, _ in HOOK_SETS[target]})
        else:
            report["skipped"].append(f"{path} ({status})")
    if not dry:
        manifest = read_manifest()
        manifest[target] = {"agents_md": agents_md, "files": files, "dirs": dirs, "kit": KIT}
        write(manifest_path(), json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", False)
    if agent_dir:
        report["models"] = {t: tiers[t] or "tool default" for t in TIERS}
    return report


def uninstall(target, dry=False):
    manifest = read_manifest()
    entry = manifest.get(target)
    report = {"target": TARGETS[target]["label"], "removed": [], "dry_run": dry}
    if not entry:
        return report
    others = [e for t, e in manifest.items() if t != target]
    shared = {d for e in others for d in e.get("dirs", [])}
    for path in entry.get("files", []):
        if os.path.isfile(path) and GENERATED in read(path):
            if not dry:
                os.remove(path)
            report["removed"].append(path)
    for path in entry.get("dirs", []):
        if path in shared:
            continue
        if os.path.isfile(os.path.join(path, MARKER)):
            if not dry:
                shutil.rmtree(path)
            report["removed"].append(path)
    spec = TARGETS[target]
    removed_hooks = uninstall_hooks(target, target_home(target), dry) if spec.get("hooks") else None
    if removed_hooks:
        report["removed"].append(removed_hooks)
    if spec.get("config"):
        rule = os.path.join(target_home(target), *spec["instructions"][1].split("/"))
        path, status = set_kilo_instructions(target_home(target), rule, dry, remove=True)
        if status == "written":
            report["removed"].append(path + " (instructions entry)")
    agents_md = entry.get("agents_md")
    if agents_md and START in read(agents_md):
        rest = without_block(read(agents_md))
        if not dry:
            if rest.strip():
                write(agents_md, rest, False)
            else:
                os.remove(agents_md)
        report["removed"].append(agents_md + " (kit block)")
    if not dry:
        manifest.pop(target, None)
        write(manifest_path(), json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", False)
    return report


def main():
    args = sys.argv[1:]
    target = args[args.index("--target") + 1] if "--target" in args and len(args) > args.index("--target") + 1 else None
    if target not in TARGETS:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    dry = "--dry-run" in args
    report = uninstall(target, dry) if "--uninstall" in args else install(target, dry, "--no-hooks" not in args)
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
