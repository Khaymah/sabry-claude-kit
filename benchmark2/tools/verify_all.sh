#!/usr/bin/env bash
set -euo pipefail
ROOT=/home/user/bench2
OUT=$ROOT/VERIFY.md
WS=/tmp/claude-0/bench_ws
{
  echo "# Verification log"
  echo
  echo "Generated by \`tools/verify_all.sh\` on $(date -u +%Y-%m-%dT%H:%MZ). Each workspace is built with \`tools/build_ref.sh\` (base + \`reference/broken\`, plus \`reference/fixed\` for the fixed run) and judged by \`hidden_check.py\`. Runtime is the wall time of one \`hidden_check.py\` run."
  echo
  echo "| Case | Broken pass/total | Fixed pass/total | Broken runtime | Fixed runtime | OK |"
  echo "|---|---|---|---|---|---|"
} > "$OUT"
for D in "$ROOT"/cases/*/; do
  C=$(basename "$D")
  declare -A R T
  for K in broken fixed; do
    bash "$ROOT/tools/build_ref.sh" "$C" "$K" "$WS/$C/$K" >/dev/null
    S=$(date +%s.%N)
    J=$(python3 "$ROOT/hidden_check.py" "$C" "$WS/$C/$K" 2>"$WS/$C/$K.log")
    E=$(python3 -c "print(f'{$(date +%s.%N) - $S:.1f}s')")
    R[$K]=$(python3 -c "import json,sys; d=json.loads(sys.argv[1]); print(f\"{d['passed']}/{d['total']}\")" "$J")
    T[$K]=$E
  done
  OK=$(python3 -c "
b,f='${R[broken]}','${R[fixed]}'
bp,bt=map(int,b.split('/')); fp,ft=map(int,f.split('/'))
print('yes' if bp<bt and fp==ft and ft>0 else 'NO')")
  echo "| $C | ${R[broken]} | ${R[fixed]} | ${T[broken]} | ${T[fixed]} | $OK |" >> "$OUT"
  echo "$C ${R[broken]} ${R[fixed]} $OK"
done
